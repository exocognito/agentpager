// A real version 2 QR code for https://agentpager.me/start, drawn as an example of what an agent shows.
const ROWS = [
  "1111111010011100001111111",
  "1000001011101100101000001",
  "1011101000111111001011101",
  "1011101000100100001011101",
  "1011101011110010001011101",
  "1000001010010110101000001",
  "1111111010101010101111111",
  "0000000010111001100000000",
  "1110011011101001111110011",
  "0101010101100101101101011",
  "0010001000011101001011101",
  "1011000101001010011001000",
  "1101111011010001101100001",
  "0001010101011001101100011",
  "1111001000111101101001101",
  "0010110011110010010111000",
  "1111001010110011111110010",
  "0000000010111101100010001",
  "1111111000010000101010001",
  "1000001011100011100010011",
  "1011101001011001111110010",
  "1011101000111010010010110",
  "1011101011111010110111011",
  "1000001011101011111110000",
  "1111111010010000110001001",
];

export function QrPicture({ className }: { className?: string }) {
  const n = ROWS.length,
    d = ROWS.flatMap((row, y) => [...row].flatMap((m, x) => (m === "1" ? [`M${x} ${y}h1v1h-1z`] : []))).join("");
  return (
    <svg className={className} viewBox={`-2 -2 ${n + 4} ${n + 4}`} shapeRendering="crispEdges" aria-hidden="true">
      <path d={d} />
    </svg>
  );
}
