// Generator for the "Routes · replies by session state" page: every route and MCP tool, what it returns in each
// session state, and what the owner's phone shows. Run through the tldraw desktop exec API with TABLE prepended by
// records/workshop/v1/routes-table.mjs, which reads the design code and fails if a route, tool or error is missing.
const { createShapeId, toRichText } = await import('tldraw');
const GEN = 'mcards-v1-routes', PAGE = 'Routes · replies by session state';
const prior = editor.getCurrentPageId();
let page = editor.getPages().find(p => p.name === PAGE);
if (!page) { editor.createPage({ id: 'page:mcards-v1-routes', name: PAGE }); page = editor.getPages().find(p => p.name === PAGE); }
editor.setCurrentPage(page.id);
editor.deleteShapes(editor.getCurrentPageShapes().filter(s => s.meta?.gen === GEN).map(s => s.id));
const id = k => createShapeId(`${page.id.slice(5)}-${k}`);
const base = { opacity: 1, meta: { gen: GEN } };
const text = (k, x, y, w, t, o = {}) => editor.createShape({ ...base, id: id(k), type: 'text', x, y, props: { w, autoSize: false, font: 'sans', size: o.size ?? 's', color: o.color ?? 'black', textAlign: 'start', richText: toRichText(t) } });
const cell = (k, x, y, w, t, o = {}) => editor.createShape({ ...base, id: id(k), type: 'geo', x, y, props: { geo: 'rectangle', w, h: 60, color: o.color ?? 'black', labelColor: o.color ?? 'black', fill: o.fill ?? 'none', dash: 'solid', size: 's', font: o.font ?? 'sans', align: 'start', verticalAlign: 'start', richText: toRichText(t) } });

const COLUMNS = [
  ['route', 'Route', 380, 'mono'],
  ['mcp', 'MCP tool', 250, 'mono'],
  ['before', 'Before the agent acknowledges pairing', 360],
  ['live', 'Live: pairing acknowledged', 330],
  ['ended', 'Ended by either side', 300],
  ['expired', 'Expired', 220],
  ['always', 'Refused in any state', 330],
  ['phone', 'What the phone shows', 330],
];
const GROUPS = { Pages: 'Pages: the owner\'s browser, the agent\'s start documents and the MCP endpoint', Agent: 'Agent calls, over HTTPS or the MCP tool on the same row', 'Agent and phone': 'Either side', Phone: 'Phone calls, made by the web app with the phone key' };
const GAP = 4, W = COLUMNS.reduce((s, c) => s + c[2] + GAP, 0);

text('title', 0, -250, 1500, 'Routes · replies by session state', { size: 'xl' });
text('sub', 0, -170, 1500, 'Every route the product serves (design/effects/routes.ts) and the MCP tool that does the same, with what each returns in each session state and what the owner\'s phone shows. Replies and error codes come from design/effects/session.ts; the before-pairing and live cells cite the promise they come from. An error body is { "error": "<tag>", ...fields }. Generated by records/workshop/v1/routes-replies.js from routes-table.mjs.', { size: 's' });
text('legend', W - 800, -250, 800, 'Red cell: only a refusal in that state. "—": the route does not depend on that state or shows nothing there. A blank state cell: the call has no session yet.', { size: 's' });

// Cells grow to fit their text only once it is measured, so rows are drawn first, then sized and stacked: each row
// takes its tallest cell's height and the next row starts below it.
const rows = [];
const row = (k, values, o = {}) => {
  let x = 0;
  const ids = COLUMNS.map(([col, , w, font], i) => {
    const v = values[i] ?? '';
    const refusal = !o.header && /^[45]\d\d [A-Z]/.test(v) && col !== 'route' && col !== 'mcp';
    cell(`${k}-${col}`, x, 0, w, v, { font: o.header ? 'sans' : font ?? 'sans', color: refusal ? 'red' : 'black', fill: o.header ? 'semi' : 'none' });
    x += w + GAP;
    return id(`${k}-${col}`);
  });
  rows.push({ ids });
};
row('head', COLUMNS.map(c => c[1]), { header: true });
let group = null;
for (const r of TABLE) {
  if (r.group !== group) {
    group = r.group;
    text(`group-${r.key}`, 0, 0, W, GROUPS[group] ?? group, { size: 'm' });
    rows.push({ label: id(`group-${r.key}`) });
  }
  const route = `${r.route}\n${r.caller}${r.returns ? `\n→ ${r.returns}` : ''}`;
  row(r.key, [route, r.mcp || '—', r.before, r.live, r.ended || (r.before || r.live ? '—' : ''), r.expired || (r.before || r.live ? '—' : ''), r.always || '—', r.phone || '—']);
}
await new Promise(resolve => setTimeout(resolve, 400));
let y = 0;
for (const r of rows) {
  if (r.label) { y += 24; editor.updateShapes([{ id: r.label, type: 'text', y }]); y += 48; continue; }
  const h = Math.max(...r.ids.map(i => { const s = editor.getShape(i); return s.props.h + s.props.growY; }));
  editor.updateShapes(r.ids.map(i => ({ id: i, type: 'geo', y, props: { h, growY: 0 } })));
  y += h + GAP;
}

editor.setCurrentPage(prior);
await helpers.saveDoc();
return { page: page.id, rows: TABLE.length };
