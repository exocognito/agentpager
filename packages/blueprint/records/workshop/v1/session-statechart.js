const arrow = (k, from, to, label, color, fa, ta, o = {}) => {
  const a = id(k);
  editor.createShape({ ...base, id: a, type: 'arrow', x: 0, y: 0, props: { color, labelColor: color, size: color === 'green' || color === 'blue' ? 'm' : 's', dash: o.dash ?? 'solid', bend: o.bend ?? 0, labelPosition: o.labelPosition ?? 0.5, font: 'sans', richText: toRichText(label), start: { x: 0, y: 0 }, end: { x: 1, y: 0 } } });
  editor.createBindings([
    { type: 'arrow', fromId: a, toId: id(from), props: { terminal: 'start', normalizedAnchor: { x: fa[0], y: fa[1] }, isExact: false, isPrecise: true } },
    { type: 'arrow', fromId: a, toId: id(to), props: { terminal: 'end', normalizedAnchor: { x: ta[0], y: ta[1] }, isExact: false, isPrecise: true } },
  ]);
};
